"use client";

import { Component, type ErrorInfo, type ReactNode } from "react";

// A successful capability probe does not guarantee that the real renderer can allocate a context.
export class SceneBoundary extends Component<{ children: ReactNode; onFailure: () => void }, { failed: boolean }> {
  state = { failed: false };
  static getDerivedStateFromError() { return { failed: true }; }
  componentDidCatch(_error: Error, _info: ErrorInfo) { this.props.onFailure(); }
  render() { return this.state.failed ? null : this.props.children; }
}
